const router = require('express').Router()
const auth = require('../middleware/auth')
const ctrl = require('../controllers/workoutSessionController')
router.use(auth)
router.get('/volume-trend', ctrl.getVolumeTrend)
router.get('/', ctrl.list)
router.post('/', ctrl.start)
router.get('/:id', ctrl.getOne)
router.put('/:id/finish', ctrl.finish)
router.delete('/:id', ctrl.remove)
router.post('/:id/sets', ctrl.addSet)
router.put('/:id/sets/:setId', ctrl.updateSet)
router.delete('/:id/sets/:setId', ctrl.removeSet)
module.exports = router