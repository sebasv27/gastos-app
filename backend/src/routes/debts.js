const router = require('express').Router()
const auth = require('../middleware/auth')
const ctrl = require('../controllers/debtController')
router.use(auth)
router.get('/', ctrl.list)
router.post('/', ctrl.create)
router.get('/plan', ctrl.plan)
router.get('/advice/latest', ctrl.latestAdvice)
router.post('/advice', ctrl.advice)
router.post('/advice/telegram', ctrl.sendTelegram)
router.delete('/payments/:paymentId', ctrl.removePayment)
router.put('/:id', ctrl.update)
router.delete('/:id', ctrl.remove)
router.post('/:id/payments', ctrl.addPayment)
module.exports = router
